import { expect, test, type ConsoleMessage, type Page } from '@playwright/test'

/**
 * What `build` cannot tell you: whether the artifact runs.
 *
 * This drives the *built* bundle, served under the production base path `/yagoda-crm/`,
 * through one whole visit — weight, сорт, «Разом», Прийняти — and fails on any page
 * error or console error along the way. A build that compiles and then throws on first
 * render is green in `build` and red here, which is the entire point of the row.
 */

/** Console noise that is not evidence of a broken app. Kept deliberately tiny. */
const IGNORABLE = [
  /favicon/i,
  // React DevTools nag, printed as info on some builds
  /Download the React DevTools/i,
]

/**
 * Attaches error collection before the first navigation, so a throw during initial
 * render is caught rather than missed.
 */
function collectErrors(page: Page) {
  const errors: string[] = []
  page.on('pageerror', (err) => errors.push(`pageerror: ${err.message}`))
  page.on('console', (m: ConsoleMessage) => {
    if (m.type() !== 'error') return
    const text = m.text()
    if (IGNORABLE.some((r) => r.test(text))) return
    errors.push(`console.error: ${text}`)
  })
  return errors
}

/**
 * Вхід у застосунок. З фази 4 його не оминає ЖОДЕН тест цього файлу: `App.tsx:141` тримає
 * «є кому діяти» інваріантом рендеру, тому без сесії немає ні оболонки, ні прийомки, ні
 * жодного розділу — є лише `SignInPage`.
 *
 * Пароль стоїть тут ЛІТЕРАЛОМ, і це не витік: той самий рядок надрукований на самому екрані
 * входу («Пароль в усіх один: 1111»), бо в демоверсії і пароль, і права перевіряє браузер.
 * Тягнути його сюди з `auth-mock.ts` було б і неможливо (`seed:port` не пускає), і
 * безглуздо: тест мусить набирати те саме, що набирає людина.
 *
 * Селектори — по id полів (`signin-login`, `signin-secret`), а не по підпису: підписи
 * «Логін»/«Пароль» короткі й трапляються в тексті плашки поруч, а id стоїть у розмітці
 * рівно один раз (`SignInPage.tsx`).
 *
 * ЧОГО ЦЕЙ ПОМІЧНИК НЕ ДОВОДИТЬ: він завжди подає ПРАВИЛЬНУ пару. Три причини відмови
 * (`unknown-login`, `wrong-secret`, `no-account`), які розрізняє `authenticate()`, тут не
 * виконуються жодного разу — вони перевіряються юніт-тестами `auth-mock.test.ts`, і
 * жодного рендеру тих трьох текстів не бачив ще ніхто, крім людини.
 */
async function signIn(page: Page, login: string) {
  await expect(page.getByRole('heading', { name: 'Вхід' })).toBeVisible()
  await page.locator('#signin-login').fill(login)
  await page.locator('#signin-secret').fill('1111')
  await page.getByRole('button', { name: 'Увійти' }).click()
}

test('зібраний артефакт піднімається під /yagoda-crm/ без помилок', async ({ page }) => {
  const errors = collectErrors(page)

  const response = await page.goto('./', { waitUntil: 'domcontentloaded' })
  expect(response?.status(), 'preview має віддати 200 під базовим шляхом').toBe(200)

  /*
   * ПЕРШИЙ ВИГЛЯД — ЕКРАН ВХОДУ, і перевіряється це тут окремим рядком, а не мовчазно
   * всередині `signIn()`. Причина в тому, що саме цей рядок падає, якщо гейт `App.tsx:141`
   * колись послабити до `if (!session)` або прибрати зовсім: тоді артефакт відкриється
   * одразу прийомкою — під невідомо чиїм імʼям, — а всі інші тести цього файлу лишаться
   * зеленими, бо помічник входу просто не знайде поля і впаде з іншої причини.
   *
   * Порожній `localStorage` у кожного тесту (свій контекст) робить це станом за
   * замовчуванням, а не збігом.
   */
  await expect(
    page.getByRole('heading', { name: 'Вхід' }),
    'артефакт мусить відкриватися екраном входу, а не прийомкою',
  ).toBeVisible()

  await signIn(page, 'p1')

  // If the base path were wrong the HTML would still load and every asset would 404,
  // leaving an empty shell — so assert on rendered content, not on the response alone.
  await expect(page.getByRole('heading', { name: 'Прийомка ягоди' })).toBeVisible()

  expect(errors, `помилки на старті:\n${errors.join('\n')}`).toEqual([])
})

/**
 * Панель «Стан точки» — каса й ящики просто на прийомці, щоб приймальник не йшов із
 * форми по ці числа. Тест окремий, а не рядок у обході розділів, і причина не в охайності:
 * він мусить читати НЕЗАЙМАНИЙ сід. Playwright дає кожному тесту свій контекст із порожнім
 * localStorage, а візит із тесту нижче зрушив би і касу, і склад наділу — після нього ці
 * числа звіряти вже не було б з чим.
 *
 * ЧОМУ ТУТ ЗВІРЯЮТЬСЯ ЧИСЛА, ЯКІ ВЖЕ ЗВІРЕНІ НА ІНШИХ ЕКРАНАХ. Обидва малює ІНШИЙ код:
 * склад наділу — компактний варіант `CrateStandingBar`, а суму шухляди — `PointStatePanel`,
 * який читає з `cashStanding()` поле `expectedCash`. Сусіднє поле тієї самої згортки
 * (`berryCash` = 1 616,10 ₴) відрізняється від правильного більш ніж у девʼять разів,
 * лишаючись цілком правдоподібним числом у гривнях — тобто помилка в одному слові тут
 * невидима для всього, крім рівності конкретній сумі.
 */
test('панель «Стан точки» на прийомці показує касу й склад наділу', async ({ page }) => {
  const errors = collectErrors(page)
  await page.goto('./', { waitUntil: 'domcontentloaded' })
  // Точка тут не вибирається руками: `p1` — логін приймальника Шипинок, а точку після
  // входу ставить `scopeAfterSignIn(user)` з облікового запису (`auth.ts:100-103`). Тому
  // обидва числа нижче — саме Шипинки 04.08.2026, і жодного кліку по селектору точки для
  // цього не треба.
  await signIn(page, 'p1')
  await expect(page.getByRole('heading', { name: 'Прийомка ягоди' })).toBeVisible()

  /*
   * 15 416,10 ₴ — «у шухляді» на Шипинках 04.08.2026 (docs/21 §8.4), тотожність `I57`:
   * 1 616,10 за ягоду + 13 800,00 завдатків. Те саме число звіряється на «Касі точки»
   * нижче по файлу; тут воно доводить, що панель прийомки читає САМЕ суму шухляди.
   *
   * Локатор бере сусідній <div> після підпису (PointStatePanel.tsx, `Money`), а не блок
   * цілком — інакше збіг ловився б і в рядку розкладу під сіткою. Роздільник тисяч у
   * `uk-UA` — нерозривний пробіл, тому в шаблоні `\s`, а не пробіл.
   */
  const drawerNow = page.getByText('У шухляді зараз').locator('xpath=following-sibling::div[1]')
  await expect(
    drawerNow,
    '«У шухляді зараз» на прийомці мусить показувати 15 416,10 ₴ (docs/21 §8.4)',
  ).toHaveText(/^15\s416,10\s₴$/)

  /*
   * Склад наділу тим самим локатором за формою, що й на «Ящиках»: рядок на прийомці лише
   * один, бо сторінки не змонтовані одночасно.
   */
  await expect(
    page.getByText(/^\d+ = \d+ \+ \d+ \+ \d+$/),
    'смужка складу наділу на прийомці мусить показувати 800 = 341 + 195 + 264 (docs/21 §8.4)',
  ).toHaveText('800 = 341 + 195 + 264')

  await expect(page.locator('body')).not.toContainText('NaN')
  expect(errors, `помилки на панелі «Стан точки»:\n${errors.join('\n')}`).toEqual([])
})

test('один візит проходить від ваги до «Разом»', async ({ page }) => {
  const errors = collectErrors(page)
  await page.goto('./', { waitUntil: 'domcontentloaded' })
  await signIn(page, 'p1')
  await expect(page.getByRole('heading', { name: 'Прийомка ягоди' })).toBeVisible()

  // 1 · постачальник — тригер має role="combobox", не button
  const picker = page.getByRole('combobox').filter({ hasText: 'Обрати постачальника' })
  await picker.click()
  await expect(page.getByPlaceholder('Прізвище або село…')).toBeVisible()
  const firstSupplier = page.getByRole('option').first()
  await expect(firstSupplier).toBeVisible()
  await firstSupplier.click()
  // прізвища беремо з seed через .first(), а не літералом: інакше тест ламається
  // від будь-якої зміни довідника, і його почнуть «лагодити» ослабленням перевірок
  await expect(picker).toHaveCount(0)

  // 2 · вага з тарою. Тара обовʼязкова: ReceptionPage тримає «Прийняти» вимкненою,
  // поки tareUnits === 0, бо інакше брутто пішло б у чисту вагу цілком.
  await page.locator('#gross').fill('120,50')
  // Лічильник у рядку тари — єдиний input[inputmode="numeric"] на екрані. Раніше тут
  // стояла кнопка «+10 ящ.», але швидкі кнопки з прийомки прибрано.
  await page.locator('input[inputmode="numeric"]').first().fill('10')

  // 3 · сорт із цінами дня — беремо перший доступний
  const berry = page.getByRole('button', { name: /₴\/кг$/ }).first()
  await expect(berry).toBeVisible()
  await berry.click()

  // 4 · «Разом» мусить перестати бути нулем.
  //
  // Раніше тут стояло `expect(getByText('Разом до видачі')).toBeVisible()` з коментарем
  // «саме тут падає збірка, яка рахує NaN». Це було неправдою: «Разом до видачі» — це
  // статичний <Eyebrow> (ReceptionPage.tsx:829), а сума живе в сусідньому <span>, і
  // uah(NaN) друкує рівно «NaN ₴». Тобто перевірка не могла впасти з тієї причини, яку
  // сама називала. Тепер перевіряється сама цифра.
  const totalBlock = page.getByText('Разом до видачі').locator('..')
  await expect(totalBlock).toBeVisible()
  await expect(totalBlock).not.toContainText('NaN')
  expect(
    await totalBlock.innerText(),
    '«Разом» мусить містити ненульову цифру, а не 0,00 і не NaN',
  ).toMatch(/[1-9]/)
  // Ширша сітка на весь екран: NaN у будь-якій сумі — це та сама поломка.
  await expect(page.locator('body')).not.toContainText('NaN')

  const accept = page.getByRole('button', { name: /^Прийняти/ })
  await expect(accept).toBeEnabled()
  await accept.click()

  // квитанція візиту відкривається одразу після прийомки
  const receipt = page.getByRole('dialog')
  await expect(receipt).toBeVisible()

  /*
   * ПІДПИС ПІД ДОКУМЕНТОМ — ІМʼЯ ЛЮДИНИ, А НЕ НАЗВА ТОЧКИ. Це головне, що фаза 4 обіцяла
   * («під документами дня стоїть імʼя людини, яка їх зробила»), і єдине місце в цьому
   * файлі, де перевіряється сам ланцюжок вхід → сесія → підпис у збереженому документі.
   *
   * До фази 4 `operator` брався з мапи `OPERATORS[pointId]`, тобто був властивістю ТОЧКИ:
   * два касири Шипинок (`Оксана Г.` і `Марія С.`, `seed.ts`) підписували б квитанції
   * однаково. Тепер він приходить із сесії (`store.ts`: `actorAt` → `user.name`), тому
   * рядок нижче падає і від підміни підпису на назву точки («Шипинки»), і від повернення
   * до мапи — вхід у тесті виконано під `p1`, і `Оксана Г.` — це саме той обліковий запис.
   *
   * Локатор бере сусідній <span> після підпису (`ReceiptDialog.tsx:26-31`, `Row`), а не
   * рядок цілком: інакше `toHaveText` довелося б писати регуляркою по обох половинах.
   */
  await expect(
    receipt.getByText('Приймав').locator('xpath=following-sibling::span[1]'),
    'у квитанції мусить стояти імʼя приймальника з сесії, а не назва точки',
  ).toHaveText('Оксана Г.')

  expect(errors, `помилки під час візиту:\n${errors.join('\n')}`).toEqual([])
})

/**
 * Раніше smoke відкривав рівно один екран із десяти, а blindSpot у registry казав про це
 * лише «екрани, яких тест не відкриває» — правдиво за формою, але без величини.
 *
 * Назва цього тесту раніше казала «усі розділи», і це було ширше за сам тест. Тому і назва,
 * і опис у registry перелічують РІВНО те, що обходиться: ТРИНАДЦЯТЬ відкриттів розділу,
 * різних розділів ДВАНАДЦЯТЬ («Постачальники» відкриваються двічі — під обома ролями, і це
 * навмисно). Шість приймальникових, перехід на керівника і шість під ним. У навігації
 * розділів шістнадцять (Shell.tsx:49-89), приймальникові з них видно сім.
 *
 * ПЕРЕХІД ДО КЕРІВНИКА — ЦЕ ВИХІД І ВХІД, А НЕ КНОПКА. До фази 4 тут стояв один клік по
 * перемикачу ролі «Власник», і сам той перемикач стверджував, що роль — властивість
 * ПРИСТРОЮ. З обліковими записами вона властивість людини, тому переходом тут працює
 * «Вийти» → екран входу → вхід під `owner` (`Shell.tsx:166-171`, `22-tz §18.4`). Це
 * дорожчий жест у тесті, і саме тому він тут: він єдиний у файлі проходить `signOut()`,
 * і саме він упаде, якщо перемикач ролі колись повернуть назад — назви «Власник» у
 * навігації більше немає.
 *
 * Поза обходом лишаються «Журнал», «Точки», «Тара і сорти» і картка постачальника;
 * «Прийомка» відкривається двома тестами вище.
 *
 * Стандарт для кожного розділу той самий: власний заголовок сторінки видимий, ані page
 * error, ані console error, і жодного «NaN» у тексті сторінки.
 */
test('розділи приймальника й керівника відкриваються без помилок і без NaN', async ({
  page,
}) => {
  const errors = collectErrors(page)
  await page.goto('./', { waitUntil: 'domcontentloaded' })
  await signIn(page, 'p1')
  await expect(page.getByRole('heading', { name: 'Прийомка ягоди' })).toBeVisible()

  const sections = ['Каса за день', 'Ціни дня', 'Постачальники', 'Залишки']
  for (const name of sections) {
    await page.getByRole('button', { name, exact: true }).first().click()
    // Кожен розділ мусить показати власний заголовок, а не порожню оболонку.
    // Тут чекається БУДЬ-ЯКИЙ заголовок, а не назва екрана, і це не недогляд: у цих
    // чотирьох підпис у навігації не дорівнює <h1> («Каса за день» → «Каса за <дата>»).
    await expect(page.getByRole('heading').first()).toBeVisible()
    await expect(page.locator('body')).not.toContainText('NaN')
  }

  // Клік по навігації, а не по сторінці: назва розділу може стояти й у тексті екрана
  // (напр. «Собівартість дня» у підказці на «Переважуванні»), і page-level пошук тоді
  // або впаде на strict mode, або клікне не туди.
  const nav = page.getByRole('navigation')

  /*
   * «Ящики» і «Каса точки» — розділи фаз 5-6, обидва доступні приймальникові. Обидва лежать
   * у ГОЛОВНОМУ чанку (App.tsx:27-31 їх навмисно не лінить: на точці вони відкриваються по
   * кілька разів на день), тому очікування заголовка тут — не очікування мережі.
   *
   * Різниця з чотирма вище: у цих двох підпис у навігації дослівно дорівнює <h1>, який малює
   * PageHeader (CratesPage.tsx:83, PointCashPage.tsx:92), тому заголовок шукається ПО ІМЕНІ.
   * Збіг доводить, що відкрився саме той екран, а не будь-який непорожній.
   */
  await nav.getByRole('button', { name: 'Ящики', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Ящики', exact: true })).toBeVisible()
  await expect(page.locator('body')).not.toContainText('NaN')

  /*
   * ПЕРША З ДВОХ ПЕРЕВІРОК КОНКРЕТНОГО ЧИСЛА В УСЬОМУ ОБХОДІ — і читати її треба саме так.
   *
   * Друга стоїть нижче, на «Касі точки» (15 416,10 ₴), і зʼявилася вона після рецензії
   * тестів: обхід був несиметричний — фаза 5 довозила своє число до пікселів, фаза 6 ні.
   * Решта ОДИНАДЦЯТИ відкриттів доводять рендер, відсутність помилок і відсутність «NaN»;
   * жодної суми на жодному іншому екрані цей файл не перевіряє. Навіть тест візиту вище
   * стверджує лише «не нуль і не NaN», а не рівність конкретній сумі. Тобто зелений обхід
   * НЕ означає, що числа на екранах правильні — він означає, що екрани відкрилися.
   *
   * Перевіряється тотожність складу наділу зі смужки (CrateStandingBar.tsx:89-93):
   * 800 = 341 + 195 + 264 — наділ, пустих на точці, у людей, у нас з ягодою. Чотири числа
   * взяті з наскрізного прикладу клієнтки (docs/21 §8.4, Шипинки 04.08.2026), а не з коду,
   * і той самий рядок стоїть у юніт-тестах рушія (crates.test.ts:370). Тут він доводить
   * інше: що зібраний артефакт довозить ці числа до пікселів на екрані.
   *
   * Локатор шукає рядок ЗА ФОРМОЮ (`\d+ = \d+ + \d+ + \d+`), а числа звіряє toHaveText —
   * інакше зміна складу наділу давала б «елемент не знайдено» замість читабельної різниці.
   */
  const standingIdentity = page.getByText(/^\d+ = \d+ \+ \d+ \+ \d+$/)
  await expect(
    standingIdentity,
    'смужка складу наділу мусить показувати 800 = 341 + 195 + 264 (docs/21 §8.4)',
  ).toHaveText('800 = 341 + 195 + 264')

  await nav.getByRole('button', { name: 'Каса точки', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Каса точки', exact: true })).toBeVisible()
  await expect(page.locator('body')).not.toContainText('NaN')

  /*
   * ДРУГЕ — І ОСТАННЄ — ЧИСЛО, ЗВІРЕНЕ З ДЖЕРЕЛОМ, дзеркально до складу наділу на «Ящиках».
   * До цього рядка фаза 5 довозила своє число до пікселів, а фаза 6 — ні: «Каса точки»
   * перевірялася лише на заголовок і на відсутність «NaN», тобто підміна будь-якої суми на
   * цьому екрані була б невидима, поки вона лишається числом.
   *
   * 15 416,10 ₴ — «у шухляді має бути» на Шипинках 04.08.2026 (docs/21 §8.4), і це та сама
   * тотожність `I57`: 1 616,10 за ягоду + 13 800,00 завдатків за 115 ящиків. Число взяте зі
   * спеки, а не з коду, і те саме стоїть у юніт-тестах стору (store.test.ts: expectedCash).
   * Тут воно доводить інше: що зібраний артефакт довозить його до екрана.
   *
   * Локатор бере САМЕ суму — сусідній <div> після підпису (PointCashPage.tsx:224-228), а не
   * блок цілком: інакше збіг ловився б і в рядку розкладу «ягода … + ящики …» під нею.
   * Роздільник тисяч у `uk-UA` — нерозривний пробіл, тому в шаблоні `\s`, а не пробіл.
   */
  const drawerTotal = page
    .getByText('У шухляді має бути')
    .locator('xpath=following-sibling::div[1]')
  await expect(
    drawerTotal,
    '«У шухляді має бути» мусить показувати 15 416,10 ₴ (docs/21 §8.4)',
  ).toHaveText(/^15\s416,10\s₴$/)

  /*
   * Далі — розділи керівника, і тут з'являється те, чого в чотирьох вище немає: КОЖЕН із
   * них приходить окремим чанком через React.lazy (App.tsx:39-66), а на час завантаження
   * Suspense малює каркас зі Skeleton і без жодного заголовка. Тому:
   *
   *   1. чекаємо саме на заголовок (`toBeVisible` з явним таймаутом на мережевий запит за
   *      чанком), а не читаємо DOM одразу після кліку;
   *   2. перевірку «немає NaN» робимо ПІСЛЯ того, як заголовок видимий — інакше вона
   *      міряла б каркас, у якому тексту немає взагалі, і зеленіла б ні про що.
   *
   * Заголовок шукається ПО ІМЕНІ розділу, а не `heading.first()` навмання: підпис у
   * навігації (Shell.tsx:75-86) дослівно дорівнює <h1>, який малює PageHeader
   * (bits.tsx:17), тому збіг доводить, що відкрився саме той екран, а не будь-який.
   */
  const CHUNK = 15_000

  /*
   * ВИХІД І ВХІД ПІД КЕРІВНИКОМ. `signOut()` не чіпає документів — він скидає лише сесію і
   * маршрут (`store.ts:317`), тому все, що обійдено вище, лишається на місці; змінюється
   * рівно той, хто за компʼютером.
   *
   * Маршрут «Зведення» ставить не клік, а сам вхід: `scopeAfterSignIn(user)` для власника
   * віддає `{ activePointId: 'all', route: 'dashboard' }` (`auth.ts:100-103`), а це вже
   * ленивий чанк — звідси очікування із `CHUNK` нижче.
   */
  await page.getByRole('button', { name: 'Вийти', exact: true }).click()
  await signIn(page, 'owner')

  await expect(page.getByRole('heading', { name: 'Зведення по сезону', exact: true })).toBeVisible({
    timeout: CHUNK,
  })
  await expect(page.locator('body')).not.toContainText('NaN')

  /*
   * ІМʼЯ В ШАПЦІ — те, що людина бачить замість назви ролі («на екрані видно, хто зараз за
   * компʼютером», `22-tz §18.4`). Перевіряється саме тут, після ПІДМІНИ: якби шапка
   * малювала щось зашите, вона показувала б те саме і під `p1`, і під `owner`, а цей рядок
   * стоїть після переходу від першого до другого.
   *
   * Локатор звужений до `<header>` (роль `banner`, `Shell.tsx:396`) і `exact: true`: під
   * тим самим імʼям рядком нижче стоїть роль «керівник · усі точки» з малої літери, і без
   * обмеження збіг ловився б і там.
   */
  await expect(
    page.getByRole('banner').getByText('Керівник', { exact: true }),
    'у шапці мусить стояти імʼя людини з сесії',
  ).toBeVisible()

  // Підписи — дослівно з Shell.tsx. Перші пʼять з групи «Керівництву»: два прийшли з фазою 2,
  // два з фази 3, «Перекази» — з фази 6.
  //
  // «Постачальники» — шості й особливі, тому вони тут, а не в циклі приймальника вище.
  // Розділ той самий (група «Люди та гроші», роль обидві), але КОМПОНЕНТ під власником
  // інший: SuppliersPage малює OwnerTable (`SuppliersPage.tsx`) — шість колонок із маркером
  // і сумою замість приймальникового списку. Під приймальником цей екран уже відкривався
  // вище, тобто саме керівницький вигляд був єдиним екраном фази 3, якого не рендерив
  // жоден тест. Конфлікту strict mode це не дає: локатор `nav` бере кнопку в навігації, а
  // не на сторінці, і кнопка там одна на роль.
  //
  // Різниця з першими пʼятьма, яку не варто забувати: ці пʼять приходять окремим чанком
  // через React.lazy, а SuppliersPage лежить у головному чанку (App.tsx її не лінить), тому
  // для неї очікування заголовка — не очікування мережі. Стандарт перевірки той самий.
  //
  // «Перекази» — розділ фази 6 і теж ленивий чанк (App.tsx:64-66), причому єдиний, який
  // приймальник не завантажує ЖОДНОГО разу: у Shell.tsx:84 він доступний лише власникові.
  const ownerSections = [
    'Собівартість дня',
    'Переважування',
    'Середня ціна по мережі',
    'Аркуш керівника',
    'Перекази',
    'Постачальники',
  ]
  // `nav` оголошений вище, перед приймальниковими «Ящиками»: клік по навігації, а не по
  // сторінці, потрібен в обох половинах обходу з тієї самої причини.
  for (const name of ownerSections) {
    await nav.getByRole('button', { name, exact: true }).click()
    await expect(page.getByRole('heading', { name, exact: true })).toBeVisible({ timeout: CHUNK })
    await expect(page.locator('body')).not.toContainText('NaN')
  }

  expect(errors, `помилки під час обходу розділів:\n${errors.join('\n')}`).toEqual([])
})

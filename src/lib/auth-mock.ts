import type { AuthResult, ClockTime, ISODate, User } from './types'

/**
 * Мок-«сервер» перевірки логіна й пароля.
 *
 * ⚠️ ЦЕЙ ФАЙЛ СТОЇТЬ НА МІСЦІ СЕРВЕРА, і зникає разом із його появою. Справжня перевірка
 * логіна й пароля — це те, що робить сервер, а не той компʼютер, за яким сидить людина:
 * «пароль, що зберігається й звіряється на самій точці, не підтверджує нічого: хто має
 * цей компʼютер, той має і пароль, і поміняти його може будь-хто» (`22-tz §17.2`, ряд.
 * 3287). Тобто ця перевірка НЕ доводить нічого про те, хто насправді сів за компʼютер —
 * вона повторює жест входу для демонстрації механізму, а не для захисту.
 *
 * Секрет тут лежить ПЛАЙНТЕКСТОМ, і це навмисно, а не недбалість. Хешування чи соління
 * секрету, який приїжджає в тому самому JS-бандлі, що й код, який його звіряє, — театр:
 * будь-хто, хто відкриє DevTools, читає хеш і сіль так само вільно, як плайнтекст. Вигляд
 * захисту тут гірший за його відсутність, бо створює хибне відчуття безпеки там, де її
 * немає й не може бути без спільного сервера (`23 §Р4-1`, `§Р4-2`).
 *
 * Пара «логін → секрет» — власний реєстр цього файлу, ОКРЕМИЙ від `users` (реєстру, який
 * бачить решта застосунку через знімок). Так само влаштований і справжній сервер: те, ЧИМ
 * людина входить, і те, ЩО про неї видно решті системи, — це дві різні таблиці. Тому
 * `authenticate()` бере `users` параметром, а не читає його звідкись саме тут: коли пара
 * логін/секрет підійшла, але в переданому реєстрі немає відповідного запису, це не той
 * самий випадок, що невідомий логін — це `'no-account'` (`23 §Р4-6`).
 */
const DEMO_SECRET = '1111'

/**
 * Сім акаунтів мок-«сервера» — рівно ті самі логіни, що `seed.ts` роздає своїм сімом
 * записам `User` (п'ять точок, керівник, другий касир Шипинок). Дублювання тут не помилка,
 * а форма межі: сервер не читає `seed.ts` (`seed:port`), тому власний реєстр логінів і
 * секретів він тримає сам, а не позичає в клієнтської фікстури.
 *
 * НЕ ЕКСПОРТУЄТЬСЯ. Секрет не має шляху на екран: ні прямого, ні через реекспорт зі стора.
 * Демо-панель екрана входу будується з `users` зі знімка (імʼя, роль, точка, логін — усе це
 * там уже є), а пароль стоїть у розмітці екрана літералом, який людина набирає сама.
 */
const ACCOUNTS: { login: string; secret: string }[] = [
  { login: 'owner', secret: DEMO_SECRET },
  { login: 'p1', secret: DEMO_SECRET },
  { login: 'p2', secret: DEMO_SECRET },
  { login: 'p3', secret: DEMO_SECRET },
  { login: 'p4', secret: DEMO_SECRET },
  { login: 'p5', secret: DEMO_SECRET },
  { login: 'p1b', secret: DEMO_SECRET },
]

/** Логін набирають руками на точці — тому нечутливий до регістру й крайніх пробілів. */
const normalizeLogin = (login: string) => login.trim().toLowerCase()

/**
 * Перевірка пари «логін, секрет» на місці сервера.
 *
 * `stamp` приходить ПАРАМЕТРОМ, а не через `new Date()`: бізнес-дата належить знімку
 * (`config.businessToday`), а не годиннику пристрою — той самий аргумент, що й у
 * `Reweigh.weighedDate`. Якби `authenticate()` сам ставив час, ця чиста на вигляд функція
 * стала б недетермінованою і непридатною для тесту без підробки годинника.
 *
 * Три причини відмови, а не одна — `AuthResult` пояснює чому (`types.ts`). Логін
 * нечутливий до регістру й крайніх пробілів: людина набирає його руками, і плутати
 * «P1» з «p1» немає підстав. Секрет — ЧУТЛИВИЙ: пробіл усередині чи скраю є ЗАКОННИМ
 * символом пароля, і «допомагати», тихо обрізаючи його, означало б змінювати те, що
 * людина насправді набрала.
 */
export function authenticate(
  users: User[],
  login: string,
  secret: string,
  stamp: { date: ISODate; time: ClockTime },
): AuthResult {
  const key = normalizeLogin(login)
  const account = ACCOUNTS.find((a) => normalizeLogin(a.login) === key)
  if (!account) return { ok: false, reason: 'unknown-login' }
  if (account.secret !== secret) return { ok: false, reason: 'wrong-secret' }

  const user = users.find((u) => normalizeLogin(u.login) === key)
  if (!user) return { ok: false, reason: 'no-account' }

  return {
    ok: true,
    session: { userId: user.id, startedDate: stamp.date, startedTime: stamp.time },
  }
}

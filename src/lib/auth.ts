import type { PointId, Role, Route, Session, User } from './types'

/**
 * Хто зараз за компʼютером — і кому це можна.
 *
 * ЧОМУ НЕ В `calc.ts`. `calc.ts` — це 1 835 рядків грошей і ящиків, і жодна його функція
 * не знає слова «сесія»: вона рахує суму, знаючи лише вагу, ціну і тару, а НЕ те, хто
 * зараз за компʼютером. Правила доступу — інша вісь: вони мусять лежати там, куди
 * дивляться з питанням «а кому це можна», а не «скільки це коштує». Це і є те місце,
 * яке сервер продублює ПЕРШИМ, коли зʼявиться (`06 §5.3`): перевірку прав сервер не
 * довіряє клієнту взагалі, а рахунок — довіряє лише як підказку для екрана. Змішати
 * два файли означало б, що майбутній сервер мусить розплутувати чужу арифметику, щоб
 * знайти в ній правила доступу.
 *
 * Пʼять функцій нижче — ЧИСТІ: жодного React, жодного стану, жодного виклику
 * `auth-mock.ts`. Це той самий стиль, що й у `calc.ts` — рушій, який store.ts (Задача 2)
 * лише викликає, а не переписує.
 */

/**
 * Людина за поточною сесією — або `null`.
 *
 * ЄДИНЕ місце, де сесія перетворюється на людину (`23 §Р4-5`, `§Р4-6`). Сесія носить лише
 * `userId`; ім'я, роль і точку читає саме ця функція — і саме тому перейменування людини в
 * реєстрі виправляє шапку одразу, без окремого кроку «оновити сесію».
 *
 * Сесія на `userId`, якого в реєстрі більше немає, — це те саме, що робить сервер із
 * токеном видаленого користувача: людину «розлогінюють», не помітивши цього окремим
 * прапорцем. Це ЄДИНА перевірка входу, результат якої не залежить від того, що людина
 * набрала (`22-tz §17.2`) — і саме тому вона не є захистом: реєстр лежить у тому самому
 * браузері, що й сесія, тому підмінити можна і те, і те (`23 §Р4-1`).
 */
export function sessionUser(users: User[], session: Session | null): User | null {
  if (!session) return null
  return users.find((u) => u.id === session.userId) ?? null
}

/**
 * Підпис під документом — імʼя людини з поточної сесії, а не назва точки.
 *
 * `null`, А НЕ ЗАПАСНИЙ РЯДОК. До фази 4 запасних підписів було ПʼЯТЬ: `point.name`,
 * `'Каса'`, `'Приймальник'`, назва ролі і — найгірший — `signerFor(…) ?? ownerName(…)` із
 * `calc.ts`, який виглядає як імʼя людини й тому невидимий очима (`23 §Р4-8`). Ця функція —
 * ОДИН джерельний рядок замість усіх пʼятьох (`23 §К4`): команда без сесії мусить
 * ВІДМОВИТИ, а не підписати чужим імʼям (`22-tz §18.4`).
 */
export function actorName(users: User[], session: Session | null): string | null {
  return sessionUser(users, session)?.name ?? null
}

/**
 * Роль поточної сесії — або `null`, коли сесії немає.
 *
 * `role` перестає бути власним полем стану (`23 §Р4-4`): два примірники одного факту в
 * цьому проєкті заборонені за побудовою (`seed.ts:229` — той самий аргумент, яким `USERS`
 * будується З `OPERATORS`, а не поруч із ним). `null` деградує до найсуворішого — жодна
 * перевірка `=== 'owner'` його не пропустить, тому відсутня сесія ніколи не читається як
 * «приймальник за замовчуванням».
 */
export function roleOf(users: User[], session: Session | null): Role | null {
  return sessionUser(users, session)?.role ?? null
}

/**
 * Чи може ця людина діяти на цій точці. Керівник — на будь-якій, приймальник — тільки на
 * своїй (`M12`, `C9`, `G16`). Чужа точка сьогодні закрита лише тим, що її немає в переліку
 * на екрані («поки не перевіряється сама точка» — ця функція і закриває той розрив.)
 *
 * Приймальник БЕЗ точки (`pointId` не заповнений) не діє НІДЕ, включно зі своїм же `undefined`
 * порівнюваним з `undefined`. Дозволити тут усе означало б, що зіпсований запис реєстру дає
 * ШИРШІ права, ніж правильний, — а зламані дані мусять програвати, а не вигравати.
 */
export function canActOnPoint(user: User | null, pointId: PointId): boolean {
  if (!user) return false
  if (user.role === 'owner') return true
  return user.pointId !== undefined && user.pointId === pointId
}

/**
 * Куди потрапляє людина одразу після входу — те, що досі робив `setRole` літералом
 * (`store.ts:239`): `activePointId: role === 'owner' ? 'all' : 'p1'`. Той літерал `'p1'`
 * означав, що «увійти приймальником» завжди кидало на Шипинки, хто б це не був, — бо роль
 * до фази 4 не несла точки. Тепер точка приходить із самого облікового запису людини, тому
 * другий пункт потрапляє на свій «Прийомка», а не на чужий.
 *
 * Приймальник без точки (той самий зламаний запис, якому `canActOnPoint` не дозволяє
 * НІЧОГО) навмисно НЕ падає на `'all'`: це підняло б йому scope до ширшого за звичайного
 * приймальника, а не до вужчого — рівно та підміна, від якої застерігає коментар
 * `canActOnPoint` вище. Порожній рядок не збігається з жодним `PointId` у довіднику
 * точок, тому екран точки не знайде і покаже це як «нема куди» — видиму відмову, а не
 * тиху видачу чужих прав.
 */
export function scopeAfterSignIn(user: User): { activePointId: PointId; route: Route } {
  if (user.role === 'owner') return { activePointId: 'all', route: { name: 'dashboard' } }
  return { activePointId: user.pointId ?? '', route: { name: 'reception' } }
}
